"""Run every analysis on data/processed/states.parquet and write tables, figures and results.md.

The verdict wording is generated from the numbers so the prose cannot drift from the results."""
from __future__ import annotations

import json

import numpy as np
import pandas as pd

from . import analysis as A
from . import config, model, plots

FIG = config.REPORTS / "figures"
TAB = config.REPORTS / "tables"


def md(df: pd.DataFrame, fmt: dict | None = None) -> str:
    fmt = fmt or {}
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(fmt.get(c, lambda v: str(v))(r[c]) for c in cols) + " |")
    return "\n".join(out)


def pp(v):  # fraction -> signed percentage points
    return f"{v * 100:+.1f}"


def pct(v):
    return f"{v * 100:.1f}%"


def verdict(rd: float, lo: float, hi: float) -> tuple[str, str]:
    if lo > 0:
        return "SUPPORTED", "fouling raised the leader's chance of winning, and the interval excludes zero"
    if hi < 0:
        return "REFUTED", "fouling lowered the leader's chance of winning, and the interval excludes zero"
    if rd > 0:
        return ("NOT PROVEN", "the point estimate favours fouling, but the interval includes zero, so the "
                "data cannot tell 'helps a little' from 'makes no difference'")
    return "NOT SUPPORTED", "the point estimate does not favour fouling and the interval includes zero"


def run_report(n_boot: int = 1000) -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    TAB.mkdir(parents=True, exist_ok=True)
    raw = pd.read_parquet(config.PROCESSED / "states.parquet")
    df = A.prepare(raw)
    diag = json.loads((config.PROCESSED / "states_diagnostics.json").read_text())

    ladder = A.ladder(df, n_boot)
    time_tab = A.by_time(df)
    mech = A.mechanism(df)
    pen = A.by_penalty(df)
    era = A.by_era(df)
    ftq = A.by_opp_ft(df)
    ad = A.adoption(df)
    bal = A.balance(df, ["t_entry", "to_used_leader", "to_used_opp", "q4_leader_fouls", "opp_ft_pct_prior",
                         "opp_tp_pct_prior", "leader_net_pg_prior", "opp_net_pg_prior", "home_leader", "season_c"])
    trips = model.trip_table(df)
    curve = model.curve(df, n_boot=500)
    trip_rows = df[(df.foul == 1) & (df.ft_att == 2)]
    obs_ft = float(trip_rows.ft_made.sum() / (2 * len(trip_rows)))
    opp_ft_prior = float(trip_rows.opp_ft_pct_prior.mean())

    for name, t in (("ladder", ladder), ("by_time", time_tab), ("mechanism", mech), ("by_penalty", pen),
                    ("by_era", era), ("by_opp_ft", ftq), ("adoption", ad), ("balance", bal), ("trips", trips)):
        t.to_csv(TAB / f"{name}.csv", index=False)

    plots.adoption(ad, FIG / "adoption.png")
    plots.forest(ladder.assign(lab=ladder["model"] + "\n(" + ladder["estimator"] + ")"), "lab",
                 FIG / "ladder.png", "Does fouling up 3 raise the leader's win probability?",
                 "Estimate shrinks and widens as we adjust for who fouls and when; 95% bootstrap intervals")
    sub = pd.concat([
        pen.rename(columns={"situation": "g"})[["g", "n_foul", "adj_rd", "adj_lo", "adj_hi"]],
        era.rename(columns={"era": "g"})[["g", "n_foul", "adj_rd", "adj_lo", "adj_hi"]],
        ftq.assign(g="Opponent FT%: " + ftq["opp_ft_tercile"].astype(str) + " (" + ftq["ft_pct_range"] + ")")
        [["g", "n_foul", "adj_rd", "adj_lo", "adj_hi"]]], ignore_index=True)
    sub["lab"] = sub["g"] + "\n(" + sub["n_foul"].astype(str) + " fouls)"
    plots.forest(sub, "lab", FIG / "subgroups.png", "Does it depend on the situation?",
                 ("Adjusted effect by subgroup; every interval includes zero"
                  if ((sub["adj_lo"] < 0) & (sub["adj_hi"] > 0)).all()
                  else "Adjusted effect by subgroup; some intervals exclude zero"), est="adj_rd", lo="adj_lo", hi="adj_hi")
    plots.mechanism(mech, FIG / "mechanism.png")
    plots.by_time(time_tab, FIG / "by_time.png")
    plots.breakeven(curve, FIG / "breakeven.png", observed_ft=obs_ft)

    full = ladder.iloc[3]
    label, why = verdict(full["rd"], full["rd_lo"], full["rd_hi"])
    se = (full["rd_hi"] - full["rd_lo"]) / (2 * 1.96)
    mult = (2.8 * se / full["rd"]) ** 2 if full["rd"] > 0 else float("nan")
    n_f, n_nf = int(df.foul.sum()), int((1 - df.foul).sum())

    lines = [
        "# Results: does fouling up 3 work?",
        "",
        "> Generated by `python -m foulup3.cli analyze`. Numbers below are produced by the code, not typed.",
        "",
        "## The hypothesis",
        "",
        "**H_strong:** with the leader up exactly 3 and under 24 seconds left, the opponent having the ball, "
        "the leader should foul *every single time*. We test it as: does the leader's chance of winning go up "
        "when they foul at the first chance, compared with when they don't?",
        "",
        f"## Verdict: **{label}**",
        "",
        f"After adjusting for time left, timeouts, team fouls, opponent shooting, team quality and era, the "
        f"leader's win probability is **{pp(full['rd'])} percentage points** when fouling "
        f"(95% CI {pp(full['rd_lo'])} to {pp(full['rd_hi'])}). That is {full['rd'] * 100:.1f} extra wins per 100 "
        f"such situations, and {why}.",
        "",
        f"- Sample: **{len(df):,}** situations over {raw.season.nunique()} seasons (1996-97 to 2024-25), of which "
        f"{n_f} had a foul and {n_nf:,} did not. Possession-inference conflicts: {diag['possession_conflicts']} "
        f"in {diag['games_scanned']:,} games.",
        f"- Power: the interval half-width is about {se * 1.96 * 100:.1f} pp. To confirm an effect of this size "
        f"(80% power) we would need roughly **{mult:.1f}x** as much data (about {int(n_f * mult):,} fouling cases "
        f"against the {n_f} the league produced in 29 seasons).",
        "",
        "## 1. The adjustment ladder",
        "",
        "Teams that foul are stronger and tend to do it with less time left, which flatters fouling. "
        "Each row adjusts for more.",
        "",
        "![ladder](figures/ladder.png)",
        "",
        md(ladder[["model", "estimator", "rd", "rd_lo", "rd_hi"]].rename(
            columns={"rd": "effect (pp)", "rd_lo": "lo", "rd_hi": "hi"}),
            {"effect (pp)": pp, "lo": pp, "hi": pp}),
        "",
        "Covariate balance (standardised mean difference, foul vs no foul; |SMD| < 0.1 is well balanced):",
        "",
        md(bal, {"smd_raw": lambda v: f"{v:+.2f}", "smd_weighted": lambda v: f"{v:+.2f}"}),
        "",
        "## 2. Time left",
        "",
        "![by time](figures/by_time.png)",
        "",
        md(time_tab[["group", "n_foul", "n_nofoul", "win_foul", "win_nofoul", "rd", "rd_lo", "rd_hi"]].rename(
            columns={"group": "time left", "rd": "diff (pp)", "rd_lo": "lo", "rd_hi": "hi"}),
            {"win_foul": pct, "win_nofoul": pct, "diff (pp)": pp, "lo": pp, "hi": pp}),
        "",
        "## 3. How games were settled",
        "",
        "![mechanism](figures/mechanism.png)",
        "",
        "When the foul sends the opponent to the line, ties drop sharply; but a make-both sequence shrinks the "
        "lead to one and creates a small chance of losing in regulation, which not fouling rarely does. "
        "When the leader is not yet in the penalty, the foul only buys a sideline inbound and ties do not fall.",
        "",
        md(mech[["group", "n", "win_reg_pct", "tie_to_ot_pct", "lose_reg_pct", "win_overall"]],
           {k: pct for k in ("win_reg_pct", "tie_to_ot_pct", "lose_reg_pct", "win_overall")}),
        "",
        "## 4. Subgroups",
        "",
        "![subgroups](figures/subgroups.png)",
        "",
        f"With {int(sub.n_foul.min())}-{int(sub.n_foul.max())} fouls per subgroup these intervals are wide. "
        "Treat patterns as hints, not findings.",
        "",
        md(pen[["situation", "n_foul", "n_nofoul", "naive_rd", "adj_rd", "adj_lo", "adj_hi"]],
           {k: pp for k in ("naive_rd", "adj_rd", "adj_lo", "adj_hi")}),
        "",
        md(era[["era", "n_foul", "n_nofoul", "foul_rate", "naive_rd", "adj_rd", "adj_lo", "adj_hi"]],
           {**{k: pp for k in ("naive_rd", "adj_rd", "adj_lo", "adj_hi")}, "foul_rate": pct}),
        "",
        md(ftq[["opp_ft_tercile", "ft_pct_range", "n_foul", "n_nofoul", "naive_rd", "adj_rd", "adj_lo", "adj_hi"]],
           {k: pp for k in ("naive_rd", "adj_rd", "adj_lo", "adj_hi")}),
        "",
        "## 5. Break-even free-throw percentage",
        "",
        "![break-even](figures/breakeven.png)",
        "",
        f"After a foul, the leader's win rate was {pct(trips.win[0])} / {pct(trips.win[1])} / {pct(trips.win[2])} "
        "when the opponent made 0 / 1 / 2 free throws. Making both is the worst case for the leader (the "
        "lead shrinks to 1). Rebuilding the win probability for any shooter skill gives the curve above.",
        "",
        md(trips.astype({"ft_made": int, "n": int}).rename(columns={"ft_made": "FTs made", "lose_reg": "lose in reg"}),
           {"win": pct, "tie": pct, "lose in reg": pct}),
        "",
        f"- Break-even FT%: **{('none in 40-100%' if curve['break_even'] is None else pct(curve['break_even']))}**. "
        f"The advantage is about {pp(curve['advantage'][list(curve['f']).index(0.5)])} pp against a 50% "
        f"shooter and {pp(curve['advantage'][list(curve['f']).index(0.76)])} pp at the league-average 76%.",
        f"- Players fouled on these trips shot **{pct(obs_ft)}**, below the {pct(opp_ft_prior)} their teams "
        "shoot. That suggests the player fouled is typically a weaker shooter than his team (or shoots worse "
        "under pressure), so team free-throw % is only a rough proxy for the number that matters.",
        "",
        "## Limitations",
        "",
        "- Observational data: adjustment handles what we measured. Unmeasured things (who has the ball, who "
        "gets fouled, coach quality, shot clock) may still bias the estimate.",
        "- Intentional fouls are inferred from context (leader's non-shooting foul in the window), not labelled.",
        "- 'No foul' includes later fouls (flag `fouled_later`, ~5%), so we compare 'foul at first chance' with "
        "'did not foul at first chance'.",
        "- Possession is inferred from events; it conflicted in "
        f"{diag['possession_conflicts']} of {diag['games_scanned']:,} games.",
        "- Timeouts are counted as events (coach-challenge timeouts excluded), not read from a rulebook-aware "
        "remaining count, because the rules changed over 29 seasons.",
        "- Team priors use schedule order (game id) within a season, not calendar dates.",
        "- The break-even curve rests on a few hundred two-shot trips, so its band is wide.",
        "",
    ]
    (config.REPORTS / "results.md").write_text("\n".join(lines))
    print(f"verdict: {label}; full-model effect {pp(full['rd'])} pp [{pp(full['rd_lo'])}, {pp(full['rd_hi'])}]")
